interface Element {
  number: number
  symbol: string
  name: string
  mass: string
  category: string
}

const ELEMENTS: Element[] = RAW.trim()
  .split('\n')
  .map((line) => {
    const [number, symbol, name, mass, category] = line.split('|')
    return {
      number: Number(number),
      symbol: symbol!.trim(),
      name: name!.trim(),
      mass: mass!.trim(),
      category: category!.trim(),
    }
  })

/** 元素符号 → 相对原子质量，供摩尔质量等工具复用 */
export const ATOMIC_MASS: Record<string, number> = Object.fromEntries(
  ELEMENTS.map((e) => [e.symbol, Number(e.mass)] as const),
)

